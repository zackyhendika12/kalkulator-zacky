    private void btnHasilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHasilActionPerformed
        // TODO add your handling code here:
        switch(pilih){
            case 1:
                bil2 = Double.parseDouble(String.valueOf(txtTampilan.getText()));
                jumlah = bil1+bil2;
                bil = Double.toString(jumlah);
                break;
            case 2:
                bil2 = Double.parseDouble(String.valueOf(txtTampilan.getText()));
                jumlah = bil1-bil2;
                bil = Double.toString(jumlah);
                break;
            case 3:
                bil2 = Double.parseDouble(String.valueOf(txtTampilan.getText()));
                jumlah = bil1*bil2;
                bil = Double.toString(jumlah);
                break;
            case 4:
                bil2 = Double.parseDouble(String.valueOf(txtTampilan.getText()));
                jumlah = bil1/bil2;
                bil = Double.toString(jumlah);
                break;
        }
        if(jumlah % 1 == 0) {
            txtTampilan.setText(String.valueOf((int) jumlah));
        } else {
            txtTampilan.setText(String.valueOf(jumlah));
        }
        txtTampilan.setText(bil);
    }//GEN-LAST:event_btnHasilActionPerformed

